# ────────────────────────────────────────────────────────────────────
# Bin thresholds. Each maps a real-valued feature score onto the 0–5
# integer scale the rubric requires. Documented and inspectable.
# ────────────────────────────────────────────────────────────────────

def _bin5(value: float, edges: list[float]) -> int:
    """Map value onto 0..5 using monotonic edges. len(edges) must be 5
    and represents lower bounds for scores 1..5."""
    assert len(edges) == 5
    score = 0
    for i, e in enumerate(edges, start=1):
        if value >= e:
            score = i
    return score


# ────────────────────────────────────────────────────────────────────
# Feature extraction. All on the persona's *response* text only.
# ────────────────────────────────────────────────────────────────────

def persona_text(transcript: dict, max_pairs: int = 5) -> str:
    """Return the persona-side text used for scoring.

    Mirrors the windowing in src/evaluation/inter_rater.py: only the
    first `max_pairs` persona responses that answer a tracked question
    are visible to the rater. Without this match the deterministic
    rater would score on a different surface than the LLM raters and
    the IRR comparison would be apples-to-oranges.
    """
    parts = []
    pair_count = 0
    for t in transcript.get("turns", []):
        if (t.get("role") == "persona"
                and t.get("responding_to_question_id")):
            txt = (t.get("text") or "").strip()
            if txt:
                parts.append(txt)
            pair_count += 1
            if pair_count >= max_pairs:
                break
    return "\n\n".join(parts)


def _count_patterns(patterns: list[str], text: str) -> int:
    n = 0
    for p in patterns:
        n += len(re.findall(p, text, flags=re.IGNORECASE))
    return n


def _count_words_in_set(text: str, vocab: set[str]) -> int:
    tokens = re.findall(r"[a-zA-Z'][a-zA-Z'-]*", text.lower())
    return sum(1 for t in tokens if t in vocab)


def _count_phrases_in_set(text: str, vocab: set[str]) -> int:
    """For multi-word vocabulary entries."""
    lowered = text.lower()
    return sum(lowered.count(v) for v in vocab if " " in v)


def emotional_depth(text: str) -> tuple[int, dict]:
    if not text:
        return 0, {"empty": True}
    words = re.findall(r"[a-zA-Z'][a-zA-Z'-]*", text.lower())
    n_words = max(len(words), 1)
    n_emotion = sum(1 for w in words if w in EMOTION_WORDS)
    n_hedge = _count_patterns(HEDGE_PATTERNS, text)
    n_stage = len(STAGE_DIRECTION_PAT.findall(text))

    # density per 100 words to neutralise transcript length.
    emo_density = 100 * n_emotion / n_words
    hedge_density = 100 * n_hedge / n_words
    stage_density = 100 * n_stage / n_words

    composite = emo_density + 0.5 * hedge_density + 0.5 * stage_density

    score = _bin5(composite, [0.5, 1.5, 3.0, 5.0, 7.5])
    return score, {
        "n_words": n_words, "n_emotion_words": n_emotion,
        "n_hedge_markers": n_hedge, "n_stage_directions": n_stage,
        "composite_density": round(composite, 3),
    }


def specificity(text: str) -> tuple[int, dict]:
    if not text:
        return 0, {"empty": True}
    words = re.findall(r"[a-zA-Z'][a-zA-Z'-]*", text.lower())
    n_words = max(len(words), 1)

    n_numbers = len(NUMBER_PAT.findall(text))
    n_time_phrases = _count_patterns(TIME_PHRASE_PATTERNS, text)
    n_proper = len(PROPER_NOUN_PAT.findall(text))
    n_concrete = sum(1 for w in words if w in CONCRETE_NOUN_LIST)

    composite = 100 * (n_numbers + n_time_phrases + 0.5 * n_proper + n_concrete) / n_words

    score = _bin5(composite, [0.5, 1.0, 1.8, 3.0, 5.0])
    return score, {
        "n_words": n_words, "n_numbers": n_numbers,
        "n_time_phrases": n_time_phrases, "n_proper_nouns": n_proper,
        "n_concrete_nouns": n_concrete,
        "composite_density": round(composite, 3),
    }


def latent_surfacing(text: str, encoded_dims: list[str]) -> tuple[int, dict]:
    if not text:
        return 0, {"empty": True}
    lowered = text.lower()
    surfaced = []
    misses = []
    for dim in encoded_dims:
        indicators = LATENT_INDICATORS.get(dim)
        if not indicators:
            misses.append({"dim": dim, "reason": "no_indicators_defined"})
            continue
        if any(ind in lowered for ind in indicators):
            surfaced.append(dim)
    n_encoded = len(encoded_dims)
    n_surfaced = len(surfaced)

    # Codebook anchor: 0=0; 1=1; 2=2; 3=3-4; 4=5-6; 5=7+.
    if n_surfaced == 0:
        score = 0
    elif n_surfaced == 1:
        score = 1
    elif n_surfaced == 2:
        score = 2
    elif n_surfaced <= 4:
        score = 3
    elif n_surfaced <= 6:
        score = 4
    else:
        score = 5

    return score, {
        "n_encoded": n_encoded, "n_surfaced": n_surfaced,
        "surfaced": surfaced, "misses_no_indicators": misses,
    }


def narrative_quality(text: str) -> tuple[int, dict]:
    if not text:
        return 0, {"empty": True}
    n_words = max(len(re.findall(r"\w+", text)), 1)
    n_temporal = _count_patterns(TEMPORAL_CONNECTIVES, text)
    n_causal = _count_patterns(CAUSAL_CONNECTIVES, text)
    # Reflection markers — first person + "realised/realized/learned/
    # understand now", indicates story-shaped reflection.
    reflection_pats = [
        r"\bi realised\b", r"\bi realized\b", r"\bi learned\b",
        r"\bi understand now\b", r"\blooking back\b",
        r"\bin hindsight\b",
    ]
    n_reflection = _count_patterns(reflection_pats, text)

    composite = 100 * (n_temporal + n_causal + 2 * n_reflection) / n_words
    score = _bin5(composite, [0.5, 1.0, 2.0, 3.5, 5.0])
    return score, {
        "n_words": n_words, "n_temporal_connectives": n_temporal,
        "n_causal_connectives": n_causal,
        "n_reflection_markers": n_reflection,
        "composite_density": round(composite, 3),
    }


def clinical_grounding(text: str) -> tuple[int, dict]:
    if not text:
        return 0, {"empty": True}
    n_words = max(len(re.findall(r"\w+", text)), 1)
    n_generic = _count_words_in_set(text, CLINICAL_TERMS_GENERIC)
    n_specific_single = _count_words_in_set(
        text, {t for t in CLINICAL_TERMS_SPECIFIC if " " not in t})
    n_specific_phrase = _count_phrases_in_set(
        text, {t for t in CLINICAL_TERMS_SPECIFIC if " " in t})
    n_specific = n_specific_single + n_specific_phrase

    # Specific terms weighted x3 vs generic, per codebook anchor.
    composite = 100 * (n_generic + 3 * n_specific) / n_words
    score = _bin5(composite, [0.5, 1.5, 3.0, 5.0, 7.5])
    return score, {
        "n_words": n_words, "n_generic_terms": n_generic,
        "n_specific_terms": n_specific,
        "composite_density": round(composite, 3),
    }


# ────────────────────────────────────────────────────────────────────
# Driver — score the 30 transcripts that the LLM raters scored.
# ────────────────────────────────────────────────────────────────────

def load_personas() -> dict:
    pmap = {}
    with open(PERSONAS) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            p = json.loads(line)
            pmap[p.get("composite_id", "")] = p
    return pmap


def main() -> None:
    irr = json.load(open(IRR_SCORES))
    sample_sids = sorted({r["session_id"] for r in irr})
    persona_map = load_personas()

    out_records = []
    for sid in sample_sids:
        t_path = TRANSCRIPTS / f"T_{sid}.json"
        transcript = json.load(open(t_path))
        text = persona_text(transcript)
        pid = transcript.get("persona_id", "")
        persona = persona_map.get(pid, {})
        encoded = list(persona.get("latent_dimensions", {}).keys()) \
            if isinstance(persona.get("latent_dimensions"), dict) \
            else (persona.get("latent_dimensions") or [])
        # Fallback: transcript also stores a copy.
        if not encoded:
            encoded = transcript.get("persona_latent_dimensions", [])

        d1, d1_feat = emotional_depth(text)
        d2, d2_feat = specificity(text)
        d3, d3_feat = latent_surfacing(text, encoded)
        d4, d4_feat = narrative_quality(text)
        d5, d5_feat = clinical_grounding(text)

        composite = round((d1 + d2 + d3 + d4 + d5) / 5, 1)

        out_records.append({
            "session_id": sid,
            "version": transcript.get("questionnaire_version"),
            "persona_id": pid,
            "encoded_latent_dimensions": encoded,
            "scores": {
                "emotional_depth": d1, "specificity": d2,
                "latent_surfacing": d3, "narrative_quality": d4,
                "clinical_grounding": d5,
            },
            "composite": composite,
            "features": {
                "emotional_depth": d1_feat,
                "specificity": d2_feat,
                "latent_surfacing": d3_feat,
                "narrative_quality": d4_feat,
                "clinical_grounding": d5_feat,
            },
        })

    OUT.write_text(json.dumps(out_records, indent=2, ensure_ascii=False))
    print(f"Wrote {OUT}  ({len(out_records)} transcripts)")


if __name__ == "__main__":
    main()
